/** Board order: skill players by rough ADP, then kickers, then defenses. */
export const MOCK_PLAYER_POOL: readonly Player[] = [...SKILL, ...DEPTH, ...KICKERS, ...DEFENSES];

export function poolByPosition(position: Position): Player[] {
  return MOCK_PLAYER_POOL.filter((player) => player.position === position);
}
