import type { Player, Position } from '@/types/player';
import { NFL_TEAMS, nflTeamByAbbr, nflLogoUrl } from './nflTeams';

/**
 * Dummy player pool for the simulator.
 *
 * These are recognisable NFL names used purely so the TV interface can be
 * developed and stress-tested without a live ESPN draft. Nothing here is used
 * on draft night: real picks come from ESPN, including ESPN's own player ids
 * and headshots. Ordering is a rough board order, which is all the simulator
 * needs to produce a believable draft.
 */

function p(name: string, position: Position, team: string): Player {
  const nfl = nflTeamByAbbr(team);
  return {
    name,
    position,
    nflTeamAbbr: nfl?.abbr ?? team,
    ...(nfl ? { nflTeamName: nfl.name } : {}),
    ...(nflLogoUrl(team) ? { teamLogoUrl: nflLogoUrl(team) } : {}),
  };
}

